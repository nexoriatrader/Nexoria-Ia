def test_fingerprint_dedup_version_change_and_retirement():
    source = _source()
    first = i06.assess_research_report(source, now=NOW)
    repeated = i06.assess_research_report(source, previous=first, now=NOW)
    assert _item(repeated)["lifecycle"] == "UNCHANGED"
    assert _item(repeated)["duplicate_of_previous"] is True
    changed = deepcopy(source)
    changed["markets"]["forex"]["selected"][0]["context_timeframe"]["provenance_sha256"] = "b" * 64
    newer = i06.assess_research_report(changed, previous=first, now=NOW)
    assert _item(newer)["lifecycle"] == "UPDATED"
    assert _item(newer)["fingerprint"] != _item(first)["fingerprint"]
    retired = deepcopy(source)
    retired["markets"]["forex"]["selected"].clear()
    removed = i06.assess_research_report(retired, previous=first, now=NOW)
    assert removed["research_records"] == []
    assert removed["retired_records"] == [{
        "market": "forex", "symbol": "FRXEURUSD", "lifecycle": "RETIRED",
        "lifecycle_state": "CONCLUDED",
        "reason_codes": ["NOT_PRESENT_IN_CURRENT_PUBLIC_SCAN"],
    }]



    (("markets","forex","selected",0,"context_timeframe","contexts","lower","data_quality"), "STALE", "I03_TIMEFRAME_DATA_INVALID"),
    (("markets","forex","selected",0,"context_timeframe","execution_allowed"), True, "I03_NONEXECUTION_GUARD_MISSING"),
    (("markets","forex","selected",0,"context_timeframe","alignment","state"), "BLOCKED_STRONG_CONFLICT", "I03_CONTEXT_NOT_STABLE"),

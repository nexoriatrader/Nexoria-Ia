def test_v4_opt_in_calls_existing_facade_caches_and_never_reads_user_orders(monkeypatch):
    client = _route_client(monkeypatch)
    monkeypatch.setenv("NEXORA_INTELLIGENCE_READONLY_ENABLED", "true")
    monkeypatch.setenv("NEXORA_INTELLIGENCE_I06_RESEARCH_ENABLED", "true")
    report = i06.assess_research_report(_source(), now=NOW)
    scanner = AsyncMock(return_value=report)
    monkeypatch.setattr(main, "scan_intelligence_research", scanner)
    def forbidden_session(*args, **kwargs):
        raise AssertionError("v4 must not query private account orders")
    monkeypatch.setattr(main.db, "SessionLocal", forbidden_session)
    first = client.get("/api/research/asset-scanner?version=4&expiry_minutes=5")
    assert first.status_code == 200
    assert first.json()["cached"] is False
    assert "preserved_open_contracts" not in first.json()
    assert first.json()["execution_allowed"] is False
    second = client.get("/api/research/asset-scanner?version=4&expiry_minutes=5")
    assert second.status_code == 200
    assert second.json()["cached"] is True
    assert scanner.await_count == 1
    third = client.get("/api/research/asset-scanner?version=4&expiry_minutes=15")
    assert third.status_code == 200
    assert third.json()["cached"] is False
    assert scanner.await_count == 2
    client.close()



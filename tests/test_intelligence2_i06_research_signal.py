def _item(report):
    return report["research_records"][0]


def test_public_i03_observation_is_wait_never_an_entry_instruction():
    result = i06.assess_research_report(_source(), now=NOW)
    item = _item(result)
    assert result["version"] == i06.VERSION
    assert result["orders_sent"] == 0
    assert result["trade_signal_approval_supported"] is False
    assert result["signal_outcomes_supported"] == ["WAIT", "DO NOT TRADE"]
    assert result["score_kind"] == "HEURISTIC_NOT_PROBABILISTIC"
    assert item["evidence_class"] == "CONSISTENT"
    assert item["decision"] == "WAIT"
    assert item["research_usable"] is True
    assert item["lifecycle"] == "NEW"
    assert item["valid_until_epoch"] == NOW + 60
    assert item["trade_side"] is None
    assert item["entry_epoch"] is None
    assert item["contract_expiry_minutes"] is None
    assert item["approved_for_trading"] is False
    assert item["execution_allowed"] is False
    assert "TRADE_ACTIONS_NOT_SUPPORTED" in item["reason_codes"]
    assert len(item["fingerprint"]) == 64



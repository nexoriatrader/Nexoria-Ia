-- I04 shared public-knowledge memory, additive PostgreSQL 16 migration.
-- NOT AUTHORIZED FOR PRODUCTION. No application auto-DDL. No financial/user columns.
-- Run only in a separately approved maintenance window, in one transaction.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';

-- Must coexist with the already-approved F01 schema; never recreate/stamp F01.
DO $prerequisites$
BEGIN
    IF to_regclass('nexora_schema_revisions') IS NULL
       OR NOT EXISTS (SELECT 1 FROM nexora_schema_revisions
                       WHERE revision='f01_global_fencing_v1') THEN
        RAISE EXCEPTION 'I04 prerequisite F01 formal migration missing';
    END IF;
END
$prerequisites$;

LOCK TABLE nexora_schema_revisions IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE IF NOT EXISTS intelligence_knowledge (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_key VARCHAR(64) NOT NULL UNIQUE,
    category VARCHAR(24) NOT NULL,
    market VARCHAR(64) NOT NULL,
    symbol VARCHAR(30) NOT NULL,
    timeframe_seconds INTEGER NOT NULL,
    subject VARCHAR(100) NOT NULL,
    model_version VARCHAR(64) NOT NULL,
    regime VARCHAR(40) NOT NULL,
    state VARCHAR(24) NOT NULL,
    revision INTEGER NOT NULL,
    payload_json TEXT NOT NULL,
    payload_digest VARCHAR(64) NOT NULL,
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_until TIMESTAMP WITH TIME ZONE NOT NULL,
    next_review_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reason_code VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_knowledge_revision CHECK (revision >= 1),
    CONSTRAINT ck_knowledge_timeframe CHECK (timeframe_seconds >= 0),
    CONSTRAINT ck_knowledge_validity CHECK (valid_from < valid_until)
);
CREATE TABLE IF NOT EXISTS intelligence_knowledge_evidence (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_id INTEGER NOT NULL REFERENCES intelligence_knowledge(id),
    source_type VARCHAR(32) NOT NULL,
    source_ref VARCHAR(160) NOT NULL,
    source_digest VARCHAR(64) NOT NULL,
    evidence_summary_json TEXT NOT NULL,
    recorded_revision INTEGER NOT NULL,
    origin_group VARCHAR(64) NOT NULL,
    verified BOOLEAN NOT NULL,
    observation_count INTEGER NOT NULL,
    group_size INTEGER NOT NULL,
    period_from TIMESTAMP WITH TIME ZONE NOT NULL,
    period_to TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_knowledge_evidence_digest UNIQUE (knowledge_id, source_digest),
    CONSTRAINT ck_knowledge_evidence_revision CHECK (recorded_revision >= 2),
    CONSTRAINT ck_knowledge_evidence_observations CHECK (observation_count >= 1),
    CONSTRAINT ck_knowledge_evidence_group CHECK (group_size >= 0),
    CONSTRAINT ck_knowledge_evidence_period CHECK (period_from <= period_to)
);
CREATE TABLE IF NOT EXISTS intelligence_knowledge_decisions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_id INTEGER NOT NULL REFERENCES intelligence_knowledge(id),
    revision INTEGER NOT NULL,
    from_state VARCHAR(24),
    to_state VARCHAR(24) NOT NULL,
    decision VARCHAR(40) NOT NULL,
    reason_code VARCHAR(100) NOT NULL,
    evidence_digest VARCHAR(64) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_knowledge_decision_revision UNIQUE (knowledge_id, revision),
    CONSTRAINT ck_knowledge_decision_revision CHECK (revision >= 1)
);
LOCK TABLE intelligence_knowledge, intelligence_knowledge_evidence,
           intelligence_knowledge_decisions IN ACCESS EXCLUSIVE MODE;

-- Existing wrong table/column/constraint cannot be silently accepted.
DO $validate$
DECLARE
    spec RECORD;
    actual_columns INTEGER;
    actual_constraints INTEGER;
    name_and_type RECORD;
    rel_oid OID;
BEGIN
    FOR spec IN
        SELECT * FROM (VALUES
           ('intelligence_knowledge',19,5),
           ('intelligence_knowledge_evidence',14,7),
           ('intelligence_knowledge_decisions',9,4)
        ) AS t(name, col_count, constraint_count)
    LOOP
        SELECT c.oid INTO rel_oid FROM pg_catalog.pg_class c
          JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
         WHERE n.nspname=current_schema() AND c.relname=spec.name
           AND c.relkind='r';
        IF rel_oid IS NULL THEN
            RAISE EXCEPTION 'I04 table missing or not ordinary table: %',spec.name;
        END IF;
        SELECT count(*) INTO actual_columns FROM pg_catalog.pg_attribute
         WHERE attrelid=rel_oid AND attnum>0 AND NOT attisdropped;
        SELECT count(*) INTO actual_constraints FROM pg_catalog.pg_constraint
         WHERE conrelid=rel_oid AND convalidated AND NOT condeferrable
           AND NOT condeferred;
        IF actual_columns<>spec.col_count
           OR actual_constraints<>spec.constraint_count THEN
            RAISE EXCEPTION 'I04 incompatible structure: %',spec.name;
        END IF;
    END LOOP;

    -- Check every expected field's type and NOT NULL against the catalogue.
    FOR name_and_type IN
        SELECT * FROM (VALUES
          ('intelligence_knowledge','id','integer'),
          ('intelligence_knowledge','identity_key','character varying(64)'),
          ('intelligence_knowledge','category','character varying(24)'),
          ('intelligence_knowledge','market','character varying(64)'),
          ('intelligence_knowledge','symbol','character varying(30)'),
          ('intelligence_knowledge','timeframe_seconds','integer'),
          ('intelligence_knowledge','subject','character varying(100)'),
          ('intelligence_knowledge','model_version','character varying(64)'),
          ('intelligence_knowledge','regime','character varying(40)'),
          ('intelligence_knowledge','state','character varying(24)'),
          ('intelligence_knowledge','revision','integer'),
          ('intelligence_knowledge','payload_json','text'),
          ('intelligence_knowledge','payload_digest','character varying(64)'),
          ('intelligence_knowledge','valid_from','timestamp with time zone'),
          ('intelligence_knowledge','valid_until','timestamp with time zone'),
          ('intelligence_knowledge','next_review_at','timestamp with time zone'),
          ('intelligence_knowledge','reason_code','character varying(100)'),
          ('intelligence_knowledge','created_at','timestamp with time zone'),
          ('intelligence_knowledge','updated_at','timestamp with time zone'),
          ('intelligence_knowledge_evidence','id','integer'),
          ('intelligence_knowledge_evidence','knowledge_id','integer'),
          ('intelligence_knowledge_evidence','source_type','character varying(32)'),
          ('intelligence_knowledge_evidence','source_ref','character varying(160)'),
          ('intelligence_knowledge_evidence','source_digest','character varying(64)'),
          ('intelligence_knowledge_evidence','evidence_summary_json','text'),
          ('intelligence_knowledge_evidence','recorded_revision','integer'),
          ('intelligence_knowledge_evidence','origin_group','character varying(64)'),
          ('intelligence_knowledge_evidence','verified','boolean'),
          ('intelligence_knowledge_evidence','observation_count','integer'),
          ('intelligence_knowledge_evidence','group_size','integer'),
          ('intelligence_knowledge_evidence','period_from','timestamp with time zone'),
          ('intelligence_knowledge_evidence','period_to','timestamp with time zone'),
          ('intelligence_knowledge_evidence','recorded_at','timestamp with time zone'),
          ('intelligence_knowledge_decisions','id','integer'),
          ('intelligence_knowledge_decisions','knowledge_id','integer'),
          ('intelligence_knowledge_decisions','revision','integer'),
          ('intelligence_knowledge_decisions','from_state','character varying(24)'),
          ('intelligence_knowledge_decisions','to_state','character varying(24)'),
          ('intelligence_knowledge_decisions','decision','character varying(40)'),
          ('intelligence_knowledge_decisions','reason_code','character varying(100)'),
          ('intelligence_knowledge_decisions','evidence_digest','character varying(64)'),
          ('intelligence_knowledge_decisions','recorded_at','timestamp with time zone')
        ) AS expected(tname,colname,typename)
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_catalog.pg_attribute a
            JOIN pg_catalog.pg_class c ON c.oid=a.attrelid
            JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
            WHERE n.nspname=current_schema() AND c.relname=name_and_type.tname
              AND a.attname=name_and_type.colname
              AND pg_catalog.format_type(a.atttypid,a.atttypmod)=name_and_type.typename
              AND a.attnotnull AND NOT a.attisdropped
        ) AND name_and_type.colname<>'from_state' THEN
            RAISE EXCEPTION 'I04 incompatible column %.%',
               name_and_type.tname,name_and_type.colname;
        END IF;
    END LOOP;
    -- from_state must be nullable, not accidentally made NOT NULL.
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_attribute a
        JOIN pg_catalog.pg_class c ON c.oid=a.attrelid
        JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname=current_schema()
          AND c.relname='intelligence_knowledge_decisions'
          AND a.attname='from_state'
          AND pg_catalog.format_type(a.atttypid,a.atttypmod)='character varying(24)'
          AND NOT a.attnotnull
    ) THEN
        RAISE EXCEPTION 'I04 incompatible nullable decision from_state';
    END IF;
    -- Require named PK/UNIQUE/FK/CHECK constraints including expected types.
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint p
         WHERE p.conrelid='intelligence_knowledge'::regclass
           AND p.contype='u' AND p.conname='intelligence_knowledge_identity_key_key'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint p
         WHERE p.conrelid='intelligence_knowledge_evidence'::regclass
           AND p.contype='u' AND p.conname='uq_knowledge_evidence_digest'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint p
         WHERE p.conrelid='intelligence_knowledge_decisions'::regclass
           AND p.contype='u' AND p.conname='uq_knowledge_decision_revision'
    ) THEN
        RAISE EXCEPTION 'I04 unique constraints not installed';
    END IF;
    IF (SELECT count(*) FROM pg_catalog.pg_constraint
        WHERE conrelid IN ('intelligence_knowledge_evidence'::regclass,
                          'intelligence_knowledge_decisions'::regclass)
          AND contype='f') <> 2 THEN
        RAISE EXCEPTION 'I04 evidence/decision FK missing';
    END IF;
END
$validate$;

CREATE INDEX IF NOT EXISTS ix_knowledge_search ON intelligence_knowledge
    (category, market, symbol, state);


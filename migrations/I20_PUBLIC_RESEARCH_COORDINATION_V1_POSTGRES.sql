-- Public research coordination only. Formal OFFLINE migration (not for production).
-- Depends on previously approved F01 and I04. No application startup DDL.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';

DO $pre$
BEGIN
  IF to_regclass('nexora_schema_revisions') IS NULL
     OR NOT EXISTS (SELECT 1 FROM nexora_schema_revisions
                    WHERE revision='f01_global_fencing_v1')
     OR NOT EXISTS (SELECT 1 FROM nexora_schema_revisions
                    WHERE revision='i04_knowledge_base_v1') THEN
    RAISE EXCEPTION 'Public research coordination requires formal F01 and I04 migration';
  END IF;
END
$pre$;
LOCK TABLE nexora_schema_revisions IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE IF NOT EXISTS public_research_capacity (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  dynamic_limit INTEGER NOT NULL DEFAULT 8
    CHECK (dynamic_limit BETWEEN 1 AND 8),
  budget_window TIMESTAMP WITH TIME ZONE NOT NULL,
  budget_used INTEGER NOT NULL DEFAULT 0 CHECK (budget_used BETWEEN 0 AND 60),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS public_research_tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_key VARCHAR(100) NOT NULL UNIQUE,
  status VARCHAR(16) NOT NULL
    CHECK (status IN ('PENDING','RUNNING','DONE','FAILED')),
  market VARCHAR(32) NOT NULL,
  symbol VARCHAR(30) NOT NULL,
  request_digest VARCHAR(64) NOT NULL,
  worker_id VARCHAR(48),
  fencing_token INTEGER NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  lease_until TIMESTAMP WITH TIME ZONE,
  next_eligible_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  completed_at TIMESTAMP WITH TIME ZONE,
  duration_ms INTEGER CHECK (duration_ms IS NULL OR duration_ms >= 0),
  error_code VARCHAR(80),
  research_digest VARCHAR(64),
  CONSTRAINT ck_public_research_task_fence CHECK (
    fencing_token >= 0 AND attempts >= 0
  )
);
CREATE INDEX IF NOT EXISTS ix_public_research_tasks_claim ON
  public_research_tasks(status, next_eligible_at, lease_until, created_at);

-- Refuse stale/incompatible schemas when table already existed.
DO $verify$
BEGIN
  IF (SELECT COUNT(*) FROM information_schema.columns
       WHERE table_schema=current_schema() AND table_name='public_research_capacity')<>5
     OR (SELECT COUNT(*) FROM information_schema.columns
       WHERE table_schema=current_schema() AND table_name='public_research_tasks')<>17
     OR NOT EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conrelid='public_research_tasks'::regclass AND contype='u'
     ) THEN
    RAISE EXCEPTION 'Incompatible public research coordination schema';
  END IF;
END
$verify$;

INSERT INTO public_research_capacity
  (id, dynamic_limit, budget_window, budget_used, updated_at)
VALUES (1, 8, CURRENT_TIMESTAMP, 0, CURRENT_TIMESTAMP)
ON CONFLICT (id) DO NOTHING;
DO $singleton$
BEGIN
  IF (SELECT count(*) FROM public_research_capacity)<>1 THEN
    RAISE EXCEPTION 'Public research capacity singleton corrupted';
  END IF;
END
$singleton$;
INSERT INTO nexora_schema_revisions(revision, applied_at)
VALUES ('i20_public_research_coordination_v1', CURRENT_TIMESTAMP)
ON CONFLICT (revision) DO NOTHING;
COMMIT;
